package loops;

public class forloop2 {
    public static void main(String[] args) {

        /*
         * for (int i = 0; i <= 4; i++) {
         * System.out.println("* * * *");
         * }
         */
        int count = 4;
        int i = 0;
        while (i <= count) {
            System.out.println("* * * *");
            i++;
        }
    }

}
