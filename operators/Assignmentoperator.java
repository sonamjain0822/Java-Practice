package operators;

public class Assignmentoperator {
    public static void main(String[] args) {
        int A = 55;
        int B = 67;
        System.out.println("--ASSIGNMENT OPERATORS EXAMPLE ----");
        System.out.println("assignment operator (=) : " + (A = B));
        System.out.println("add equals to : " + (A += B));
        System.out.println("subtraction equals to : " + (A -= B));
        System.out.println("multiplication equals to : " + (A *= B));
        System.out.println("division equals to : " + (A /= B));

    }

}
