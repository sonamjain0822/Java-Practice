package operators;

public class relationaloperator {
    public static void main(String[] args) {
        int A = 10;
        int B = 16;
        System.out.println("---REALTIONAL OPERATORS EXAMPLE ----");
        System.out.println("EQUAL TO OPERATOR : " + (A == B));
        System.out.println("NOT EQUAL TO OPERATOR : " + (A != B));
        System.out.println("GREATER THAN OPERATOR : " + (A > B));
        System.out.println("LESS THAN  OPERATOR : " + (A < B));
        System.out.println("GREATER THAN EQUAL TO OPERATOR : " + (A >= B));
        System.out.println("LESS THAN EQUAL TO OPERATOR : " + (A <= B));

    }

}
