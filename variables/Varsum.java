public class Varsum {
    public static void main(String[] args) {
        // sum of two integers
        System.out.println(" sum of two integers");
        System.out.println("first way to add two numbers");
        int a = 90;
        int b = 100;
        int sum = a + b;
        System.out.println(sum);

        System.out.println("second way to add two numbers");
        a = 190;
        b = 160;
        System.out.println(a + b);

        // sum of two float values
        System.out.println("sum of two float values");
        System.out.println("first way to add two numbers");
        float c = 9.90f;
        float d = 10.70f;
        float floatsum = c + d;
        System.out.println(floatsum);

        System.out.println("second way to add two numbers");
        c = 19.9f;
        d = 16.7f;
        System.out.println(c + d);

        // long values sum
        System.out.println("long values sum");
        System.out.println("first way to add two numbers");
        long e = 990678L;
        long f = 107088L;
        long longsum = e + f;
        System.out.println(longsum);

        System.out.println("second way to add two numbers");
        e = 197637547L;
        f = 163948029L;
        System.out.println(e + f);

        // double values sum
        System.out.println("double values sum");
        System.out.println("first way to add two numbers");
        double g = 9906.78;
        double h = 1070.88;
        double doublesum = g + h;
        System.out.println(doublesum);

        System.out.println("second way to add two numbers");
        g = 1976.890;
        h = 16394.789;
        System.out.println(g + h);

        // sum to char data
        System.out.println("character addition");
        System.out.println("firstway to add char data");

        String firstname = "Sonam";
        String lastname = "Jain";
        String fullname = firstname + lastname;
        System.out.println(fullname);

        System.out.println("firstway to add char data");
        firstname = "Sonam";
        lastname = "Jain";
        System.out.println(firstname + " " + lastname);

    }

}
